import { expect, test } from '@playwright/test'

test('真实幺筒开局自动录制，完成一局后刷新仍可查看，回放不干扰下一场', async ({ page }) => {
  test.setTimeout(200_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.addInitScript(() => localStorage.setItem('lianhua-guangma:audio-preferences:v1',
    JSON.stringify({ soundOn: false, bgmOn: false, effectsOn: false })))
  await page.goto('/')
  await page.getByRole('button', { name: '对局回放 →' }).click()
  await expect(page.getByTestId('replay-empty')).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.locator('.start-button').click()
  const autoplay = page.getByRole('button', { name: '开启机器人托管，自动出牌与过牌' })
  await expect(autoplay).toBeVisible({ timeout: 30_000 })
  await autoplay.click()
  await expect(page.locator('.round-settlement')).toBeVisible({ timeout: 140_000 })
  const scores = await page.locator('.round-rankings article em').allTextContents()
  await page.reload()
  await page.getByRole('button', { name: '对局回放 →' }).click()
  await expect(page.locator('.replay-row')).toHaveCount(1)
  await expect(page.locator('.replay-row')).toContainText('幺筒麻将 · 东风场')
  await expect(page.locator('.replay-row')).toContainText('新手模式')
  await page.getByRole('button', { name: '查看', exact: true }).click()
  await expect(page.getByTestId('replay-viewer')).toBeVisible()
  await expect(page.locator('.replay-viewer canvas')).toBeVisible({ timeout: 30_000 })
  const position = page.getByTestId('replay-turn').locator('i')
  const initial = await position.innerText()
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(position).not.toHaveText(initial)
  await page.keyboard.press('End')
  await page.getByRole('button', { name: '结算明细', exact: true }).click()
  const ledger = page.getByRole('dialog', { name: '回放结算明细' })
  await expect(ledger.locator('.yaotong-ledger')).toBeVisible()
  await expect(ledger.getByRole('button', { name: '导出账单' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(ledger).not.toBeVisible()
  await expect(page.getByTestId('replay-viewer')).toBeVisible()
  await page.getByTestId('replay-info-toggle').click()
  await expect(page.locator('.replay-info-scores em')).toHaveCount(4)
  expect(scores.length).toBe(4)
  await page.getByRole('button', { name: '← 返回回放列表' }).click()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.locator('.start-button').click()
  await expect(page.locator('.game-table-hud')).toBeVisible()
  expect(errors).toEqual([])
})

test('全庄场恢复旧播放器能力：切局、播放速度、视角、导出导入和手机布局', async ({ page }) => {
  test.setTimeout(120_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/tests/e2e/fixtures/yaotong-replay.html?length=16&theme=llm')
  await expect(page.locator('body')).toHaveAttribute('data-fixture', 'ready', { timeout: 60_000 })
  const saved = await page.evaluate(() => (window as unknown as { yaotongReplayFixture: { roundCount: number; finalScores: number[] } }).yaotongReplayFixture)
  await page.goto('/?theme=llm')
  await page.getByRole('button', { name: '对局回放 →' }).click()
  await expect(page.locator('.replay-row')).toContainText('全庄场')
  await expect(page.locator('.replay-row')).toContainText('老手模式')
  const downloadPromise = page.waitForEvent('download')
  await page.getByTestId('replay-export').click()
  const download = await downloadPromise
  const payload = await download.path()
  expect(download.suggestedFilename()).toContain('replay-yaotong')
  await page.getByRole('button', { name: '查看', exact: true }).click()
  await expect(page.locator('.replay-viewer canvas')).toBeVisible({ timeout: 30_000 })
  await expect(page.getByTestId('replay-wall-left')).toContainText('56')
  await page.getByRole('combobox', { name: '播放速度' }).selectOption('4')
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await expect.poll(() => page.getByTestId('replay-turn').locator('i').innerText()).not.toContain('1/')
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  await page.getByRole('button', { name: '全知视角', exact: true }).click()
  await expect(page.getByRole('button', { name: '按当时所见', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const opponentDraw = page.locator('.replay-log button[data-kind="draw"]:not(.local)').first()
  await expect(opponentDraw).toContainText('暗牌')
  await expect(opponentDraw.locator('.mahjong-tile')).toHaveCount(0)
  await page.getByRole('combobox', { name: '切换牌局' }).selectOption(String(saved.roundCount - 1))
  await page.getByRole('button', { name: '下一步', exact: true }).focus()
  await page.keyboard.press('End')
  await expect(page.getByTestId('replay-result')).toContainText('北4局')
  await page.getByTestId('replay-info-toggle').click()
  await expect(page.locator('.replay-info-scores em')).toHaveText([...saved.finalScores].sort((a, b) => b - a).map(String))
  for (const viewport of [{ width: 1280, height: 720 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(viewport)
    await expect(page.getByRole('button', { name: '← 返回回放列表' })).toBeInViewport({ ratio: 1 })
    await expect(page.getByRole('button', { name: '结算明细', exact: true })).toBeInViewport({ ratio: 1 })
    await expect(page.getByRole('button', { name: '下一步', exact: true })).toBeInViewport({ ratio: 1 })
    const overlap = await page.locator('.replay-user .user-identity').evaluate((identity) => {
      const a = identity.getBoundingClientRect(), b = document.querySelector('.replay-info-body')!.getBoundingClientRect()
      return Math.min(a.right, b.right) > Math.max(a.left, b.left) && Math.min(a.bottom, b.bottom) > Math.max(a.top, b.top)
    })
    expect(overlap, '本家头像不能盖住展开的分数面板').toBe(false)
    await page.screenshot({ path: `tmp/yaotong-replay-${viewport.width}.png`, animations: 'disabled' })
    await page.getByRole('button', { name: '结算明细', exact: true }).click()
    await expect(page.getByRole('button', { name: '关闭结算明细' })).toBeInViewport({ ratio: 1 })
    await page.getByRole('button', { name: '关闭结算明细' }).click()
  }
  await page.getByRole('button', { name: '← 返回回放列表' }).click()
  await expect(page.getByTestId('replay-list-rows')).toBeVisible()
  await expect(page.getByTestId('replay-list')).toHaveCSS('opacity', '1')
  await expect(page.getByTestId('replay-list')).not.toHaveClass(/modal-enter-active/)
  await page.screenshot({ path: 'tmp/yaotong-replay-list-mobile.png', animations: 'disabled' })
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.getByTestId('replay-empty')).toBeVisible()
  await page.getByTestId('replay-import-input').setInputFiles(payload!)
  await expect(page.locator('.replay-row')).toHaveCount(1)
  await page.getByRole('button', { name: '查看', exact: true }).click()
  await expect(page.getByTestId('replay-viewer')).toBeVisible()
  expect(errors).toEqual([])
})
